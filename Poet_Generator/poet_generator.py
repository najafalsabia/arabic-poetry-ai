# NOTE: run this in a shell before executing the script, not as part of it:
# pip install openai

from google import genai
from openai import OpenAI
from sentence_transformers import SentenceTransformer

model = SentenceTransformer("BAAI/bge-m3")

import chromadb

chroma_client = chromadb.PersistentClient(path="chroma_db")

collection = chroma_client.get_collection("arabic_poetry")

client = OpenAI(
    api_key="API KEY"
)

poet = " جرير"
theme = "هجاء"
topic = "الكذب"


theme_filter = f"قصائد {theme}"

query = f"قصائد {poet} في {theme}"

query_embedding = model.encode(query).tolist()

results = collection.query(
    query_embeddings=[query_embedding],
    where={
        "$and": [
            {"poet": poet},
            {"theme": theme_filter}
        ]
    },
    n_results=3
)

titles = []

for meta in results["metadatas"][0]:
    title = meta["title"]

    if title not in titles:
        titles.append(title)

print(f"Retrieved {len(titles)} unique poems")

examples = ""

for i, doc in enumerate(results["documents"][0], 1):

    # Extract only the poem part
    poem = doc.split("Poem:")[-1].strip()

    # Keep only the first 12 verses
    verses = poem.split("\n")
    poem = "\n".join(verses[:12])

    examples += f"""
Example {i}

{poem}

----------------------------------------

"""

print(examples[:4000])

# Create The Prompt

prompt = f"""
You are an expert Arabic poet.

Study the STYLE of the following poems.

Do NOT copy any verse.
Do NOT repeat any sentence.
Do NOT continue the examples.

Learn only:
- vocabulary
- rhythm
- imagery
- expressions

Style Examples:

{examples}

===================================

Now write a completely NEW poem.

Topic: {topic}
Poet style: {poet}
Theme: {theme_filter}

Requirements:
- Around 10 verses.
- Classical Arabic.
- Original wording.
- Do not copy any line from the examples.

Return ONLY the poem.
"""

# Generate The Poem

response = client.chat.completions.create(
    model="gpt-4.1-mini",
    messages=[
        {
            "role": "user",
            "content": prompt
        }
    ],
    temperature=0.9
)

print(response.choices[0].message.content)

